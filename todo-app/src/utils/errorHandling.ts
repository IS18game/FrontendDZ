import axios from 'axios';
import type { ОшибкаПриложения } from '@/types';
import { записатьСобытиеОшибки } from '@/services/monitoring';

export type ТипОшибки = 'сетевая' | 'валидационная' | 'бизнес';

export interface IКлассифицированнаяОшибка {
  тип: ТипОшибки;
  сообщениеПользователю: string;
  исходнаяОшибка: unknown;
}

export const классифицироватьОшибку = (ошибка: unknown): IКлассифицированнаяОшибка => {
  if (axios.isAxiosError(ошибка)) {
    return {
      тип: 'сетевая',
      сообщениеПользователю: 'Не удалось выполнить запрос. Попробуйте ещё раз.',
      исходнаяОшибка: ошибка,
    };
  }

  if (ошибка instanceof Error && ошибка.name === 'ZodError') {
    return {
      тип: 'валидационная',
      сообщениеПользователю: ошибка.message,
      исходнаяОшибка: ошибка,
    };
  }

  return {
    тип: 'бизнес',
    сообщениеПользователю: ошибка instanceof Error ? ошибка.message : 'Произошла ошибка. Попробуйте ещё раз.',
    исходнаяОшибка: ошибка,
  };
};

export const создатьОшибкаПриложения = (ошибка: unknown, запасноеСообщение: string): ОшибкаПриложения => {
  const классифицированнаяОшибка = классифицироватьОшибку(ошибка);

  return {
    тип: классифицированнаяОшибка.тип === 'валидационная' ? 'валидация' : 'сервис',
    код: классифицированнаяОшибка.тип === 'валидационная' ? 'НЕКОРРЕКТНЫЕ_ДАННЫЕ' : 'ОШИБКА_СЕРВИСА',
    сообщение: классифицированнаяОшибка.сообщениеПользователю || запасноеСообщение,
    ...(классифицированнаяОшибка.тип === 'валидационная' ? { поля: {} } : {}),
  } as ОшибкаПриложения;
};

export const записатьОшибка = (ошибка: unknown): void => {
  записатьСобытиеОшибки(классифицироватьОшибку(ошибка));
};

export const получитьСообщениеОшибки = (ошибка: ОшибкаПриложения | null): string =>
  ошибка?.сообщение ?? '';

